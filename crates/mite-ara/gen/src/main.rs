//! Writes `crates/mite-ara/src/sys.rs`: the ARA C API (ARAInterface.h) as Rust, with bindgen's
//! layout tests (each struct's size and field offsets against the C compiler's).

fn main() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let header = root.join("ara_api/ARAInterface.h");
    let out = root.join("src/sys.rs");
    let bindings = bindgen::Builder::default()
        .header(header.to_string_lossy())
        .clang_arg("-xc")
        .allowlist_type("ARA.*")
        .allowlist_var("kARA.*")
        .allowlist_function("ARA.*")
        .derive_default(true)
        .layout_tests(true)
        .generate_comments(false)
        .raw_line("//! Generated by crates/mite-ara/gen from ara_api/ARAInterface.h (ARA SDK 2.3,")
        .raw_line("//! Copyright (c) 2012-2025 Celemony Software GmbH, Apache License 2.0). Do not edit.")
        .raw_line("#![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, dead_code, clippy::all, unsafe_op_in_unsafe_fn)]")
        .generate()
        .expect("bindgen");
    bindings.write_to_file(&out).expect("write sys.rs");
    println!("wrote {}", out.display());
}
