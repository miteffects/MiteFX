//! Markdown tables with a verdict per row, written into the measured section of a compare doc
//! (between `<!-- measured:begin -->` and `<!-- measured:end -->`; the rest is hand-written).

use std::fmt::Write as _;
use std::path::Path;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Verdict {
    /// Equal to FabFilter or better.
    Pass,
    /// Within the stated tolerance of FabFilter.
    Close,
    Fail,
    /// No verdict (a reference row).
    None,
}

impl Verdict {
    /// A lower-is-better metric: Mite's `mite` against FabFilter's `fab`, `tol` the "close" margin.
    pub fn lower(mite: f64, fab: f64, tol: f64) -> Self {
        if mite <= fab + 1e-9 {
            Self::Pass
        } else if mite <= fab + tol {
            Self::Close
        } else {
            Self::Fail
        }
    }

    fn cell(self) -> &'static str {
        match self {
            Self::Pass => "**pass**",
            Self::Close => "**close**",
            Self::Fail => "**fail**",
            Self::None => "",
        }
    }
}

pub struct Row {
    pub cells: Vec<String>,
    pub verdict: Verdict,
}

impl Row {
    /// `label | fab | mite | verdict` for a lower-is-better metric.
    /// Compared at the precision shown: equal as printed is a pass.
    pub fn lower(label: &str, fab: f64, mite: f64, tol: f64, decimals: usize) -> Self {
        let round = |x: f64| (x * 10f64.powi(decimals as i32)).round() / 10f64.powi(decimals as i32);
        Self { cells: vec![label.to_owned(), format!("{fab:.decimals$}"), format!("{mite:.decimals$}")], verdict: Verdict::lower(round(mite), round(fab), tol) }
    }
}

pub struct Table {
    pub title: String,
    pub note: String,
    pub header: Vec<String>,
    pub rows: Vec<Row>,
}

impl Table {
    pub fn new(title: &str, note: &str, header: &[&str]) -> Self {
        Self { title: title.to_owned(), note: note.to_owned(), header: header.iter().map(|s| (*s).to_owned()).collect(), rows: Vec::new() }
    }

    pub fn push(&mut self, row: Row) {
        self.rows.push(row);
    }

    fn markdown(&self) -> String {
        let mut s = format!("### {}\n\n{}\n\n", self.title, self.note);
        let _ = writeln!(s, "| {} |", self.header.join(" | "));
        let _ = writeln!(s, "|{}|", self.header.iter().map(|_| "---").collect::<Vec<_>>().join("|"));
        for r in &self.rows {
            let mut cells = r.cells.clone();
            if self.header.len() > cells.len() {
                cells.push(r.verdict.cell().to_owned());
            }
            let _ = writeln!(s, "| {} |", cells.join(" | "));
        }
        s
    }
}

/// Counts of pass / close / fail over `tables`.
fn summary(tables: &[Table]) -> String {
    let count = |v: Verdict| tables.iter().flat_map(|t| &t.rows).filter(|r| r.verdict == v).count();
    format!("**{} pass · {} close · {} fail**", count(Verdict::Pass), count(Verdict::Close), count(Verdict::Fail))
}

/// Replaces the measured section of `doc` with `tables` (creating the markers at the end when
/// the doc has none).
pub fn write(doc: &Path, tables: &[Table], stamp: &str) -> Result<(), String> {
    let old = std::fs::read_to_string(doc).unwrap_or_default();
    let mut body = format!("<!-- measured:begin -->\n_Generated by `cargo xtask compare` on {stamp}. Do not edit by hand._\n\n{}\n\n", summary(tables));
    for t in tables {
        body.push_str(&t.markdown());
        body.push('\n');
    }
    body.push_str("<!-- measured:end -->");
    let new = match (old.find("<!-- measured:begin -->"), old.find("<!-- measured:end -->")) {
        (Some(a), Some(b)) if b > a => format!("{}{}{}", &old[..a], body, &old[b + "<!-- measured:end -->".len()..]),
        _ => format!("{old}\n## Measured\n\n{body}\n"),
    };
    std::fs::write(doc, new).map_err(|e| format!("{}: {e}", doc.display()))
}
